export const GLOSSARY_LETTERS = Array.from(
  new Set(GLOSSARY_ITEMS.map((item) => item.letter)),
).sort();

export function filterGlossary({ query = "", letter = "", group = "all" } = {}) {
  const q = String(query || "").trim().toLowerCase().replace(/[\s\-_/（）()]+/g, "");
  const matched = GLOSSARY_ITEMS.filter((item) => {
    if (group && group !== "all" && item.group !== group) return false;
    if (letter && item.letter !== letter) return false;
    if (!q) return true;
    const hay = `${item.code} ${item.zh} ${item.en} ${item.summary} ${item.aliases || ""}`
      .toLowerCase()
      .replace(/[\s\-_/（）()]+/g, "");
    return hay.includes(q);
  });
  if (!q) return matched;
  const score = (item) => {
    const codeNorm = item.code.toLowerCase().replace(/[\s\-_/（）()]+/g, "");
    if (codeNorm === q) return 0;
    if (codeNorm.startsWith(q)) return 1;
    if (codeNorm.includes(q)) return 2;
    if (item.zh.toLowerCase().includes(q)) return 3;
    return 4;
  };
  return matched.sort((a, b) => score(a) - score(b));
}
